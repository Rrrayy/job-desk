/** 相对今天偏移若干天的某个时刻 */
function at(now: Date, daysAgo: number, hour = 10, min = 0): Date {
  const d = new Date(now.getTime());
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, min, 0, 0);
  return d;
}

/** 未来的第 n 个某个星期几（ISO 1-7），至少 minAhead 天后 */
function nextWeekday(now: Date, weekday: number, minAhead: number): Date {
  const d = new Date(now.getTime());
  for (let i = minAhead; i < minAhead + 14; i += 1) {
    const candidate = new Date(now.getTime());
    candidate.setDate(candidate.getDate() + i);
    if (weekdayOf(candidate) === weekday) return candidate;
  }
  return d;
}

/** 今天的某个时刻 */
function todayAt(now: Date, hour: number, min = 0): Date {
  const d = new Date(now.getTime());
  d.setHours(hour, min, 0, 0);
  return d;
}

/** 未来第 n 天的纯日期（YYYY-MM-DD），给截止日期用 */
function inDays(now: Date, n: number): string {
  const d = new Date(now.getTime());
  d.setDate(d.getDate() + n);
  return toDateISO(d);
}

